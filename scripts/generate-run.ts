/**
 * Runs the engine over examples/ledger and writes what the two apps display.
 *
 * - apps/web/src/run.generated.ts: the run the marketing site prints.
 * - apps/console/src/bundle.generated.ts: the same run as an audit bundle -
 *   records and a run summary, built by the code `qed check` and `qed export`
 *   use - which the console opens exactly as it opens one a reader loads.
 *
 * Nothing either app shows is typed in. A change to the engine shows up on
 * both rather than drifting away from them.
 *
 * Run: pnpm generate:run
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { runPair, type ModulePair } from "@qed/engine";
import {
  parseBundle,
  serialiseBundle,
  BUNDLE_KIND,
  type AttestationRecord,
  type QedBundle,
} from "@qed/ui/model";

import { runSummary } from "../packages/cli/src/export.ts";
import { buildRecord, formatUtc } from "../packages/cli/src/records.ts";
import { ENGINE } from "../packages/cli/src/version.ts";

const root = process.cwd();
const read = (name: string) =>
  readFileSync(join(root, "examples/ledger", name), "utf8");

const INPUTS = 2000;
const COMMAND = "qed check --base origin/main";

const modules: ModulePair[] = [
  {
    path: "billing/ledger.ts",
    base: read("base.ts"),
    head: read("head.ts"),
  },
  {
    path: "orders/handlers.ts",
    base: read("impure.ts"),
    head: read("impure-head.ts"),
  },
];

const started = Date.now();
const { result, details } = runPair(modules, { inputs: INPUTS, command: COMMAND });
const elapsed = Date.now() - started;
const run = { ...result, duration: `${(elapsed / 1000).toFixed(1)}s` };

const tolerances = [
  ...new Set([...details.values()].flatMap((d) => d.tolerancesApplied)),
];

/* ------------------------------------------------------------- the site */

const header = `/**
 * GENERATED by scripts/generate-run.ts. Do not edit.
 *
 * The output of a real engine run over examples/ledger, with ${INPUTS}
 * generated inputs per function. Every count, counterexample and obstruction
 * below was produced by running the code, not written by hand.
 *
 * Controls: clock frozen, rng seeded, network, timers, crypto and the
 * high-resolution clock denied, relative imports pinned, others refused.
 * Tolerances applied: ${tolerances.length > 0 ? tolerances.join("; ") : "none"}.
 */
import type { RunResult } from "@qed/ui";
`;

writeFileSync(
  join(root, "apps/web/src/run.generated.ts"),
  `${header}
export const GENERATED_RUN: RunResult = ${JSON.stringify(run, null, 2)};
`,
  "utf8",
);

/* ---------------------------------------------------------- the console */

const BUNDLE_FILE = join(root, "apps/console/src/bundle.generated.ts");

/**
 * The bundle written last time, if it still parses.
 *
 * A run takes a fraction of a second and a timestamp to the minute, so every
 * build would otherwise rewrite the file with a new time and a new duration
 * and nothing else. When the records say the same things, the previous file
 * stands - including the time it really was made.
 */
function previous(): QedBundle | undefined {
  if (!existsSync(BUNDLE_FILE)) return undefined;
  const match = /EXAMPLE_BUNDLE = (".*");/s.exec(readFileSync(BUNDLE_FILE, "utf8"));
  if (!match?.[1]) return undefined;
  const parsed = parseBundle(JSON.parse(match[1]) as string);
  return parsed.ok ? parsed.bundle : undefined;
}

/** A record without the fields that only say when it was made. */
const content = (record: AttestationRecord) => ({
  ...record,
  timestamp: "",
  digest: "",
});

const before = previous();
const context = {
  repository: "examples/ledger",
  commit: "example",
  timestamp: formatUtc(new Date()),
  engine: ENGINE,
};
const records = await Promise.all(
  run.runs.map((r) => buildRecord(r, details.get(`${r.path}:${r.symbol}`), context)),
);

const unchanged =
  before !== undefined &&
  JSON.stringify(before.records.map(content)) === JSON.stringify(records.map(content));

if (!unchanged) {
  const bundle: QedBundle = {
    kind: BUNDLE_KIND,
    repository: context.repository,
    runs: [runSummary(run, records, context)],
    records,
    signatures: [],
    tags: {},
  };
  writeFileSync(
    BUNDLE_FILE,
    `/**
 * GENERATED by scripts/generate-run.ts. Do not edit.
 *
 * The audit bundle the console opens by default: a real engine run over
 * examples/ledger, recorded by the code \`qed check\` uses and bundled as
 * \`qed export\` would bundle it. It is unsigned, because signing needs a CI
 * identity this script does not have, and it says so.
 *
 * The text is kept exactly as written, so the digest the console shows for
 * it is the digest of these bytes.
 */
export const EXAMPLE_BUNDLE = ${JSON.stringify(serialiseBundle(bundle))};
`,
    "utf8",
  );
}

const counts = run.runs.reduce<Record<string, number>>((acc, r) => {
  acc[r.verdict.state] = (acc[r.verdict.state] ?? 0) + 1;
  return acc;
}, {});

process.stdout.write(
  `generated run: ${run.runs.length} functions - ` +
    Object.entries(counts)
      .map(([state, n]) => `${n} ${state}`)
      .join(", ") +
    (unchanged ? " (console bundle unchanged)" : " (console bundle rewritten)") +
    `\n`,
);
